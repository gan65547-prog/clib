/* ── internal constants ────────────────────────────────────────────────── */

#define MEDIAMTX_STARTUP_TIMEOUT_MS  3000
#define MEDIAMTX_POLL_INTERVAL_MS    200
#define SHUTDOWN_GRACE_MS            500

/* ── internal helpers ──────────────────────────────────────────────────── */

static int
str_copy(char *dst, const char *src, size_t dst_size)
{
    if (!dst || !src || dst_size == 0) return -1;
    size_t n = strlen(src);
    if (n >= dst_size) return -1;
    memcpy(dst, src, n + 1);
    return 0;
}

/* Try to get a non-loopback IPv4 address for the URL. */
static int
get_host_ip(char *buf, size_t buf_size)
{
#if defined(__APPLE__) || defined(__linux__)
    struct ifaddrs *ifaddr, *ifa;
    if (getifaddrs(&ifaddr) < 0) goto fallback;
    for (ifa = ifaddr; ifa; ifa = ifa->ifa_next) {
        if (!ifa->ifa_addr || ifa->ifa_addr->sa_family != AF_INET) continue;
        if (ifa->ifa_flags & IFF_LOOPBACK) continue;
        struct sockaddr_in *sin = (struct sockaddr_in *)ifa->ifa_addr;
        const char *ip = inet_ntoa(sin->sin_addr);
        if (ip && ip[0] != '\0') {
            str_copy(buf, ip, buf_size);
            freeifaddrs(ifaddr);
            return 0;
        }
    }
    freeifaddrs(ifaddr);
#endif
fallback:
    str_copy(buf, "127.0.0.1", buf_size);
    return 0;
}

/* Poll until mediamtx is listening on its RTSP port. */
static int
wait_for_port(int port, int timeout_ms)
{
    int elapsed = 0;
    struct sockaddr_in addr;
    memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_port   = htons((uint16_t)port);
    addr.sin_addr.s_addr = inet_addr("127.0.0.1");

    while (elapsed < timeout_ms) {
        int fd = socket(AF_INET, SOCK_STREAM, 0);
        if (fd < 0) goto wait;
        if (connect(fd, (struct sockaddr *)&addr, sizeof(addr)) == 0) {
            close(fd);
            return 0;
        }
        close(fd);
wait:
        usleep((useconds_t)(MEDIAMTX_POLL_INTERVAL_MS * 1000));
        elapsed += MEDIAMTX_POLL_INTERVAL_MS;
    }
    return -1;
}

/* Write mediamtx YAML config file. Returns 0 on success. */
static int
write_mediamtx_config(const char *path, const char *stream_path, int port)
{
    FILE *f = fopen(path, "w");
    if (!f) return -1;
    fprintf(f,
        "# Auto-generated by ml_rtsp_server\n"
        "rtspAddress: :%d\n"
        "rtmpAddress: :0\n"
        "hlsAddress: :0\n"
        "webrtcAddress: :0\n"
        "paths:\n"
        "  %s:\n"
        "    source: publisher\n",
        port, stream_path);
    fclose(f);
    return 0;
}

/* ── internal structure ────────────────────────────────────────────────── */

struct ml_rtsp_server_s {
    ml_rtsp_server_cfg_t cfg;
    ml_pool_t           *pool;

    pid_t  mediamtx_pid;
    pid_t  ffmpeg_pid;

    int    pipe_fd;         /* write end of pipe to ffmpeg stdin */
    char   config_path[256];
    char   stream_url[256];
    char   error_msg[256];

    /* dynamic string storage for ffmpeg argv — owned by srv */
    char   ffmpeg_url[256];
    char   ffmpeg_vsize[32];
    char   ffmpeg_frate[16];
    char   ffmpeg_bitrate[32];

    int    running;
};

/* Build the ffmpeg command-line arguments.
 * argv array is pool-allocated.  String constants are used directly
 * (no strdup).  Dynamic strings live in srv->ffmpeg_* fixed buffers.
 * Caller must free argv with pool->f_free(pool, argv). */
static char **
build_ffmpeg_cmd(ml_rtsp_server_t *srv, int *argc_out)
{
    const ml_rtsp_server_cfg_t *cfg = &srv->cfg;
    char **argv = srv->pool->f_alloc(srv->pool, 32 * sizeof(char *));
    if (!argv) return NULL;

    const char *bin = cfg->ffmpeg_path ? cfg->ffmpeg_path : "ffmpeg";
    const char *vcodec = cfg->ffmpeg_vcodec ? cfg->ffmpeg_vcodec : "libx264";
    const char *preset = cfg->ffmpeg_preset ? cfg->ffmpeg_preset : "ultrafast";
    const char *tune   = cfg->ffmpeg_tune   ? cfg->ffmpeg_tune   : "zerolatency";

    const char *pix;
    switch (cfg->pix_fmt) {
    case ML_RTSP_PIX_BGR24:   pix = "bgr24";   break;
    case ML_RTSP_PIX_YUV420P: pix = "yuv420p"; break;
    default:                  pix = "nv12";    break;
    }

    snprintf(srv->ffmpeg_url, sizeof(srv->ffmpeg_url),
             "rtsp://127.0.0.1:%d/%s", cfg->port, cfg->stream_path);
    snprintf(srv->ffmpeg_vsize, sizeof(srv->ffmpeg_vsize),
             "%dx%d", cfg->width, cfg->height);
    if (cfg->fps_den == 1)
        snprintf(srv->ffmpeg_frate, sizeof(srv->ffmpeg_frate),
                 "%d", cfg->fps_num);
    else
        snprintf(srv->ffmpeg_frate, sizeof(srv->ffmpeg_frate),
                 "%d/%d", cfg->fps_num, cfg->fps_den);

    int idx = 0;
    argv[idx++] = (char *)bin;
    argv[idx++] = (char *)"-loglevel";
    argv[idx++] = (char *)"error";
    argv[idx++] = (char *)"-f";
    argv[idx++] = (char *)"rawvideo";
    argv[idx++] = (char *)"-pixel_format";
    argv[idx++] = (char *)pix;
    argv[idx++] = (char *)"-video_size";
    argv[idx++] = srv->ffmpeg_vsize;
    argv[idx++] = (char *)"-framerate";
    argv[idx++] = srv->ffmpeg_frate;
    argv[idx++] = (char *)"-i";
    argv[idx++] = (char *)"pipe:0";
    argv[idx++] = (char *)"-c:v";
    argv[idx++] = (char *)vcodec;
    argv[idx++] = (char *)"-preset";
    argv[idx++] = (char *)preset;
    argv[idx++] = (char *)"-tune";
    argv[idx++] = (char *)tune;
    argv[idx++] = (char *)"-g";
    argv[idx++] = (char *)"30";
    if (cfg->ffmpeg_bitrate > 0) {
        snprintf(srv->ffmpeg_bitrate, sizeof(srv->ffmpeg_bitrate),
                 "%d", cfg->ffmpeg_bitrate);
        argv[idx++] = (char *)"-b:v";
        argv[idx++] = srv->ffmpeg_bitrate;
    }
    argv[idx++] = (char *)"-f";
    argv[idx++] = (char *)"rtsp";
    argv[idx++] = (char *)"-rtsp_transport";
    argv[idx++] = (char *)"tcp";
    argv[idx++] = srv->ffmpeg_url;
    argv[idx] = NULL;

    *argc_out = idx;
    return argv;
}

/* ── internal structure ────────────────────────────────────────────────── *//* ── lifecycle ─────────────────────────────────────────────────────────── */

ml_rtsp_server_t *
ml_rtsp_server_create(const ml_rtsp_server_cfg_t *cfg, ml_pool_t *pool)
{
    /* ── validate config ──────────────────────────────────────────────── */
    ml_rtsp_server_cfg_t local_cfg = ML_RTSP_SERVER_CFG_DEFAULT;
    if (!pool) return NULL;
    if (cfg) local_cfg = *cfg;

    if (local_cfg.width <= 0 || local_cfg.height <= 0) return NULL;
    if (local_cfg.fps_num <= 0) local_cfg.fps_num = 30;
    if (local_cfg.fps_den <= 0) local_cfg.fps_den = 1;
    if (!local_cfg.stream_path || !local_cfg.stream_path[0])
        local_cfg.stream_path = "stream";
    if (local_cfg.port <= 0) local_cfg.port = 8554;

    /* ── check binaries exist ─────────────────────────────────────────── */
    const char *mediamtx_bin = local_cfg.mediamtx_path
                               ? local_cfg.mediamtx_path : "mediamtx";
    const char *ffmpeg_bin   = local_cfg.ffmpeg_path
                               ? local_cfg.ffmpeg_path : "ffmpeg";

    {
        char test_cmd[512];
        snprintf(test_cmd, sizeof(test_cmd), "command -v %s >/dev/null 2>&1",
                 mediamtx_bin);
        if (system(test_cmd) != 0) return NULL;
        snprintf(test_cmd, sizeof(test_cmd), "command -v %s >/dev/null 2>&1",
                 ffmpeg_bin);
        if (system(test_cmd) != 0) return NULL;
    }

    /* ── allocate ─────────────────────────────────────────────────────── */
    ml_rtsp_server_t *srv = pool->f_alloc(pool, sizeof(*srv));
    if (!srv) return NULL;
    memset(srv, 0, sizeof(*srv));
    srv->pool       = pool;
    srv->cfg        = local_cfg;
    srv->pipe_fd    = -1;
    srv->mediamtx_pid = -1;
    srv->ffmpeg_pid   = -1;

    /* ── write mediamtx config ────────────────────────────────────────── */
    snprintf(srv->config_path, sizeof(srv->config_path),
             "/tmp/ml_rtsp_%d.yml", getpid());
    if (write_mediamtx_config(srv->config_path, srv->cfg.stream_path,
                               srv->cfg.port) < 0) {
        str_copy(srv->error_msg, "failed to write mediamtx config",
                 sizeof(srv->error_msg));
        pool->f_free(pool, srv);
        return NULL;
    }

    /* ── start mediamtx ───────────────────────────────────────────────── */
    {
        pid_t pid = fork();
        if (pid < 0) {
            unlink(srv->config_path);
            str_copy(srv->error_msg, "fork failed for mediamtx",
                     sizeof(srv->error_msg));
            pool->f_free(pool, srv);
            return NULL;
        }
        if (pid == 0) {
            /* child: mediamtx */
            execlp(mediamtx_bin, mediamtx_bin, srv->config_path, (char *)NULL);
            _exit(127);
        }
        srv->mediamtx_pid = pid;
    }

    /* wait for mediamtx to listen */
    if (wait_for_port(srv->cfg.port, MEDIAMTX_STARTUP_TIMEOUT_MS) < 0) {
        snprintf(srv->error_msg, sizeof(srv->error_msg),
                 "mediamtx did not start on port %d within %d ms",
                 srv->cfg.port, MEDIAMTX_STARTUP_TIMEOUT_MS);
        kill(srv->mediamtx_pid, SIGTERM);
        waitpid(srv->mediamtx_pid, NULL, 0);
        srv->mediamtx_pid = -1;
        unlink(srv->config_path);
        pool->f_free(pool, srv);
        return NULL;
    }

    /* ── build ffmpeg command ─────────────────────────────────────────── */
    int    ffmpeg_argc = 0;
    char **ffmpeg_argv = build_ffmpeg_cmd(srv, &ffmpeg_argc);
    if (!ffmpeg_argv) {
        snprintf(srv->error_msg, sizeof(srv->error_msg),
                 "failed to build ffmpeg command");
        kill(srv->mediamtx_pid, SIGTERM);
        waitpid(srv->mediamtx_pid, NULL, 0);
        srv->mediamtx_pid = -1;
        unlink(srv->config_path);
        pool->f_free(pool, srv);
        return NULL;
    }

    /* ── create pipe ──────────────────────────────────────────────────── */
    int pipefds[2];
    if (pipe(pipefds) < 0) {
        str_copy(srv->error_msg, "pipe() failed", sizeof(srv->error_msg));
        pool->f_free(pool, ffmpeg_argv);
        kill(srv->mediamtx_pid, SIGTERM);
        waitpid(srv->mediamtx_pid, NULL, 0);
        srv->mediamtx_pid = -1;
        unlink(srv->config_path);
        pool->f_free(pool, srv);
        return NULL;
    }

    /* ── start ffmpeg ─────────────────────────────────────────────────── */
    {
        pid_t pid = fork();
        if (pid < 0) {
            str_copy(srv->error_msg, "fork failed for ffmpeg",
                     sizeof(srv->error_msg));
            pool->f_free(pool, ffmpeg_argv);
            close(pipefds[0]);
            close(pipefds[1]);
            kill(srv->mediamtx_pid, SIGTERM);
            waitpid(srv->mediamtx_pid, NULL, 0);
            srv->mediamtx_pid = -1;
            unlink(srv->config_path);
            pool->f_free(pool, srv);
            return NULL;
        }
        if (pid == 0) {
            /* child: ffmpeg — connect stdin to pipe read end */
            dup2(pipefds[0], STDIN_FILENO);
            close(pipefds[0]);
            close(pipefds[1]);
            execvp(ffmpeg_bin, ffmpeg_argv);
            _exit(127);
        }
        srv->ffmpeg_pid = pid;
    }

    close(pipefds[0]);  /* parent only writes */
    srv->pipe_fd = pipefds[1];
    pool->f_free(pool, ffmpeg_argv);

    /* ── build URL ────────────────────────────────────────────────────── */
    {
        char host_ip[64];
        get_host_ip(host_ip, sizeof(host_ip));
        snprintf(srv->stream_url, sizeof(srv->stream_url),
                 "rtsp://%s:%d/%s",
                 host_ip, srv->cfg.port, srv->cfg.stream_path);
    }

    srv->running = 1;
    return srv;
}

void
ml_rtsp_server_destroy(ml_rtsp_server_t *srv)
{
    if (!srv) return;
    srv->running = 0;

    /* close pipe to ffmpeg (triggers EOF → ffmpeg exits) */
    if (srv->pipe_fd >= 0) {
        close(srv->pipe_fd);
        srv->pipe_fd = -1;
    }

    /* wait for ffmpeg to exit */
    if (srv->ffmpeg_pid > 0) {
        int status;
        usleep(SHUTDOWN_GRACE_MS * 1000);
        /* if still alive, force-kill */
        if (waitpid(srv->ffmpeg_pid, &status, WNOHANG) == 0) {
            kill(srv->ffmpeg_pid, SIGTERM);
            usleep(200 * 1000);
            if (waitpid(srv->ffmpeg_pid, &status, WNOHANG) == 0) {
                kill(srv->ffmpeg_pid, SIGKILL);
                waitpid(srv->ffmpeg_pid, &status, 0);
            }
        }
        srv->ffmpeg_pid = -1;
    }

    /* stop mediamtx */
    if (srv->mediamtx_pid > 0) {
        kill(srv->mediamtx_pid, SIGTERM);
        int status;
        usleep(500 * 1000);
        if (waitpid(srv->mediamtx_pid, &status, WNOHANG) == 0) {
            kill(srv->mediamtx_pid, SIGKILL);
            waitpid(srv->mediamtx_pid, &status, 0);
        }
        srv->mediamtx_pid = -1;
    }

    unlink(srv->config_path);
    srv->pool->f_free(srv->pool, srv);
}

/* ── frame feeding ─────────────────────────────────────────────────────── */

int
ml_rtsp_server_feed(ml_rtsp_server_t *srv,
                     const uint8_t *data, size_t len)
{
    if (!srv || !data || len == 0) return -1;
    if (!srv->running || srv->pipe_fd < 0) return -1;

    /* Non-blocking check: poll pipe for writability (quick check only) */
    size_t written = 0;
    while (written < len) {
        ssize_t n = write(srv->pipe_fd, data + written, len - written);
        if (n < 0) {
            if (errno == EAGAIN || errno == EWOULDBLOCK) {
                /* pipe buffer full — skip this frame */
                return -1;
            }
            if (errno == EPIPE) {
                srv->running = 0;
                str_copy(srv->error_msg, "ffmpeg pipe broken",
                         sizeof(srv->error_msg));
                return -1;
            }
            return -1;
        }
        if (n == 0) {
            srv->running = 0;
            str_copy(srv->error_msg, "pipe write returned 0",
                     sizeof(srv->error_msg));
            return -1;
        }
        written += (size_t)n;
    }
    return 0;
}

/* ── query ─────────────────────────────────────────────────────────────── */

const char *
ml_rtsp_server_url(ml_rtsp_server_t *srv)
{
    if (!srv || !srv->running) return NULL;
    return srv->stream_url;
}

int
ml_rtsp_server_running(ml_rtsp_server_t *srv)
{
    if (!srv || !srv->running) return 0;
    /* double-check: ffmpeg still alive? */
    if (srv->ffmpeg_pid > 0) {
        int status;
        if (waitpid(srv->ffmpeg_pid, &status, WNOHANG) != 0) {
            /* process exited */
            srv->running = 0;
            return 0;
        }
    }
    return 1;
}

const char *
ml_rtsp_server_error(ml_rtsp_server_t *srv)
{
    if (!srv) return NULL;
    return srv->error_msg[0] ? srv->error_msg : NULL;
}
